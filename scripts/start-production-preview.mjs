import { readFileSync, existsSync } from "node:fs";
import { cp } from "node:fs/promises";
import { parseEnv } from "node:util";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { spawn } from "node:child_process";
import { createServer } from "node:net";

const root=fileURLToPath(new URL("../",import.meta.url));
const settings=join(root,".env.production-preview.local");
if(!existsSync(settings))throw new Error("Configure .env.production-preview.local with the production workspace ID before starting this preview.");
for(const name of [".env.local",".env.production-preview.local"]){const path=join(root,name);if(existsSync(path))Object.assign(process.env,parseEnv(readFileSync(path,"utf8")));}
const workspace=process.env.PROJECT_OS_WORKSPACE_ID;
if(!workspace||workspace==="local_seedy"||!process.env.SUPABASE_SECRET_KEY)throw new Error("The preview needs the existing production workspace and Supabase server credentials.");
process.env.PROJECT_OS_BACKEND="supabase";
process.env.PROJECT_OS_REQUIRE_EXISTING_WORKSPACE="true";
process.env.PROJECT_OS_INITIALIZATION_MODE="preserve-history";
const port=Number(process.env.PORT||3002);
if(!Number.isSafeInteger(port)||port<1024||port>65535)throw new Error("Invalid local preview port.");
process.env.PROJECT_OS_APP_URL=`http://127.0.0.1:${port}`;
process.env.PROJECT_OS_DATA_DIR=resolve(root,process.env.PROJECT_OS_DATA_DIR||".node-runtime/production-preview");
process.env.PORT=String(port);
process.env.HOSTNAME="127.0.0.1";
const networkHelper=new URL("./preview-network.mjs",import.meta.url).href;
process.env.NODE_OPTIONS=`${process.env.NODE_OPTIONS||""} --import=${networkHelper}`.trim();
const dist=process.env.PROJECT_OS_NODE_DIST_DIR===".next-node-qa"?".next-node-qa":".next-node";
const standalone=join(root,dist,"standalone");
if(!existsSync(join(standalone,"server.js")))throw new Error("Run node scripts/build-node.mjs first.");
await new Promise((resolve,reject)=>{const probe=createServer();probe.once("error",()=>reject(new Error(`Port ${port} is occupied. No existing server was stopped.`)));probe.listen(port,"127.0.0.1",()=>probe.close(resolve));});
const response=await fetch(`${process.env.SUPABASE_URL}/rest/v1/workspace_bootstrap?user_id=eq.${encodeURIComponent(workspace)}&select=user_id`,{headers:{apikey:process.env.SUPABASE_SECRET_KEY,Authorization:`Bearer ${process.env.SUPABASE_SECRET_KEY}`},signal:AbortSignal.timeout(15000)});
if(!response.ok)throw new Error(`Production workspace verification failed (${response.status}).`);
if(!(await response.json()).length)throw new Error("The production workspace was not found. No demo data will be imported.");
await cp(join(root,dist,"static"),join(standalone,dist,"static"),{recursive:true});
await cp(join(root,"public"),join(standalone,"public"),{recursive:true});
console.log(`Full Project OS preview: ${process.env.PROJECT_OS_APP_URL}/login · live production projects and files, real Supabase login.`);
const child=spawn(process.execPath,[join(root,"scripts/start-node.mjs")],{cwd:root,stdio:"inherit",env:process.env});
for(const signal of ["SIGINT","SIGTERM"])process.on(signal,()=>child.kill(signal));
child.on("error",()=>{console.error("Unable to start the production preview.");process.exitCode=1;});
child.on("exit",code=>{process.exitCode=code??1;});
